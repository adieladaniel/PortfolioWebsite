"""
Cuts the gyroscope render into one transparent disc per ring, plus the core.

    python scripts/hero-sprites/build_gyro_sprites.py path/to/gyro.jpg

Writes public/hero/gyro/*.webp and src/data/hero/gyroGeometry.ts.

The render is a top-down view of concentric rings. Every ring is a circle around
the same centre, so a ring is just the pixels between two radii: no edge detection
needed. The centre is found by searching for the point where the radial brightness
profile is sharpest, and the radii below were read off that profile. In the page each
disc is tilted with CSS 3D transforms about its own centre.

Radii are for a 1376x768 render and are scaled by width / 1376, so a 2K render of the
same picture works unchanged. A different render needs new RINGS: print the radial
profile (see centre_search) and read the ring edges off it.
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

BASE_W = 1376
# name, inner radius, outer radius (1376x768 space), outer to inner
RINGS = [
    ("outer_frame", 294, 343),
    ("obsidian", 235, 283),
    ("copper", 194, 224),
    ("frosted", 148, 183),
    ("knurled", 112, 138),
    ("steel", 63, 100),
    ("core", 0, 62),
]
STUD_REACH = 372  # the four mounting studs poke out past the outer frame
FEATHER = 1.0     # soft edge width, 1376px space


def centre_search(gray, s):
    h, w = gray.shape
    yy, xx = np.mgrid[0:h, 0:w]
    best = None
    for cx in np.arange(684.5, 689.6, 0.5) * s:
        for cy in np.arange(381.0, 386.1, 0.5) * s:
            r = np.hypot(xx - cx, yy - cy)
            size = int(400 * s)
            idx = np.clip(r.astype(int), 0, size - 1)
            sums = np.bincount(idx.ravel(), weights=gray.ravel(), minlength=size)[: size - 20]
            cnt = np.bincount(idx.ravel(), minlength=size)[: size - 20]
            score = np.abs(np.diff(sums / np.maximum(cnt, 1))).sum()
            if best is None or score > best[0]:
                best = (score, cx, cy)
    return best[1], best[2]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("--out", default="public/hero/gyro")
    ap.add_argument("--data", default="src/data/hero/gyroGeometry.ts")
    ap.add_argument("--scale", type=float, default=1.0, help="resize the sprites by this factor on the way out")
    a = ap.parse_args()

    img = cv2.imread(a.image)
    h, w = img.shape[:2]
    s = w / BASE_W
    rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
    bg = np.median(img[int(5 * s):int(60 * s), int(5 * s):int(60 * s)].reshape(-1, 3), axis=0)
    dist = np.abs(img.astype(float) - bg).max(axis=2)
    cx, cy = centre_search(gray, s)
    print(f"centre {cx:.1f}, {cy:.1f}")

    yy, xx = np.mgrid[0:h, 0:w]
    r = np.hypot(xx - cx, yy - cy).astype(np.float32)
    f = FEATHER * s

    out_dir = Path(a.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    rings = []
    for name, r0, r1 in RINGS:
        r0, r1 = r0 * s, r1 * s
        inner = np.clip((r - (r0 - f)) / (2 * f), 0, 1) if name != "core" else 1.0
        alpha = np.asarray(inner * np.clip(((r1 + f) - r) / (2 * f), 0, 1), np.float32)
        reach = r1 + 4 * s
        if name == "outer_frame":
            stud = (r > r1) & (r < STUD_REACH * s) & (dist > 30) & ((np.abs(xx - cx) < 12 * s) | (np.abs(yy - cy) < 12 * s))
            alpha = np.maximum(alpha, stud.astype(np.float32))
            alpha[int(640 * s):, int(1200 * s):] = 0  # corner watermark
            reach = STUD_REACH * s
        half = int(np.ceil(reach))
        x0, y0 = int(round(cx)) - half, int(round(cy)) - half
        rgba = np.dstack([rgb, (alpha * 255).astype(np.uint8)])[y0:y0 + 2 * half, x0:x0 + 2 * half]
        im = Image.fromarray(rgba, "RGBA")
        if a.scale != 1.0:
            im = im.resize((round(im.width * a.scale), round(im.height * a.scale)), Image.LANCZOS)
        im.save(out_dir / f"{name}.webp", "WEBP", quality=88, method=6)
        rings.append({"name": name, "file": f"{name}.webp", "half": half, "inner": round(r0, 1), "outer": round(r1, 1)})
        print(f"{name:12s} r {r0:6.1f}-{r1:6.1f} sprite {2 * half}px")

    geom = {
        "size": {"w": w, "h": h},
        "centre": {"x": round(cx, 1), "y": round(cy, 1)},
        "rings": rings,
    }
    ts = (
        "/** Generated by scripts/hero-sprites/build_gyro_sprites.py. Every sprite is a square of side 2*half centred on `centre`. */\n"
        "import type { GyroGeometry } from './types';\n\n"
        f"export const gyroGeometry: GyroGeometry = {json.dumps(geom, indent=2)};\n"
    )
    Path(a.data).parent.mkdir(parents=True, exist_ok=True)
    Path(a.data).write_text(ts, encoding="utf-8")
    total = sum(p.stat().st_size for p in out_dir.glob("*.webp"))
    print(f"wrote {len(rings)} sprites ({total // 1024} KB) to {out_dir}")


if __name__ == "__main__":
    main()
